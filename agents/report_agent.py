from crewai import Agent, Task

from config import AGENT_MAX_ITERATIONS
from llm import llm


def create_report_agent() -> Agent:
    """
    Create the Report Agent.

    This agent is responsible only for presenting the final
    structured football intelligence generated by previous agents.

    It never searches, reasons, evaluates, recommends or
    changes the conclusions.
    """

    return Agent(

        role="Football Intelligence Report Writer",

        goal=(
            "Transform structured football intelligence into a "
            "professional, visually organized HTML document that "
            "communicates the information as clearly as possible."
        ),

        backstory=(

            "You are the final agent in an advanced Football "
            "Intelligence platform."

            "Every previous agent already completed the reasoning."

            "Your responsibility is communication, not analysis."

            "You never search the web."

            "You never scrape webpages."

            "You never perform football analysis."

            "You never evaluate evidence."

            "You never compare players."

            "You never recommend players."

            "You never modify conclusions."

            "You never invent information."

            "You preserve every conclusion exactly as received."

            "Before writing the report, understand the structure, "
            "meaning and relationships contained in the structured "
            "football intelligence."

            "Allow the information itself to determine the report "
            "organization."

            "Create a professional HTML document whose layout, "
            "hierarchy and presentation naturally emerge from the "
            "content instead of following predefined templates."

            "Prioritize readability, clarity, visual organization "
            "and professional presentation."
        ),

        llm=llm,

        max_iter=AGENT_MAX_ITERATIONS,
    )


def create_report_task(
    agent: Agent,
    recommendation_task: Task,
) -> Task:
    """
    Create the Report Task.
    """

    return Task(

        description="""
Use the structured football intelligence provided in the task context.

Study the complete information before generating the report.

Understand the user's original objective together with the final football intelligence.

Produce a professional HTML document that communicates the information
clearly, accurately and naturally.

Allow the information itself to determine the report structure.

Preserve every conclusion exactly as received.

Do not modify the football intelligence.

Do not invent information.

Do not perform football reasoning.

Do not search the web.

Do not scrape webpages.

Return ONLY a complete HTML document.

Do not return Markdown.

Do not return explanations.
""",

        expected_output=(
            "A complete standalone HTML document that professionally "
            "presents the structured football intelligence."
        ),

        agent=agent,

        context=[
            recommendation_task,
        ],
    )